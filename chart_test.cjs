const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const source=fs.readFileSync('main.go','utf8').split('const chartHTML = `')[1].split('<script>')[1].split('</script>')[0];
const ctx=vm.createContext({document:{getElementById:()=>({})},fetch:()=>new Promise(()=>{}),addEventListener:()=>{}});
vm.runInContext(source,ctx);
const now=Date.UTC(2026,8,22,12);
const row=(ip,thr,time,mbps)=>({ip,thr,time,mbps,target:'同名节点',t:'2026-09-22 12:00:00'});
const rows=[row('a:5201','1',now,0),row('a:5201','4',now-1000,40),row('b:5201','1',now-86400000*40,80),row('a:5201','1',now-86400000,20)];
const groups=ctx.groupChartRows(rows);
assert.equal(groups.length,3,'same names must not merge addresses or stream counts');
const g=groups.find(g=>g.ip==='a:5201'&&g.streams==='1');
assert.equal(g.rows[0].mbps,20);assert.equal(g.rows[1].mbps,0);
assert.equal(ctx.selectChartRows(rows,'a:5201','1','all',now).length,2);
assert.equal(ctx.selectChartRows(rows,'','','7',now).length,3);
assert.equal(ctx.selectChartRows(rows,'b:5201','','30',now).length,0);
assert.equal(ctx.selectChartRows(rows,'','','all',now).length,4);
assert.equal(ctx.selectChartRows(rows,'missing','','all',now).length,0);
assert.equal(rows[0].time,now,'selection must not reorder source data');
const stats=ctx.summarizeChartRows(rows);
assert.equal(stats.count,4);assert.equal(stats.nodes,2);assert.equal(stats.average,35);
assert.equal(stats.latest.mbps,0,'zero Mbps is a valid latest measurement');assert.equal(stats.peak.mbps,80);
assert.equal(ctx.summarizeChartRows([]).latest,null);
console.log('PASS: series identity, sorting, combined filters, time range, empty results, average, peak, zero result, source preservation');
